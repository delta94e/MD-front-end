const FILE_NAMES = ["Report", "Proposal", "Budget", "Design", "Contract", "Invoice", "Notes", "Presentation", "Analysis", "Roadmap", "Spec", "Review"];
const FILE_TYPES = ["pdf", "docx", "xlsx", "png", "jpg", "mp4", "txt", "zip", "pptx", "csv"];
const OWNERS     = ["Alice Chen", "Bob Park", "Carol Smith", "Dave Jones", "Eve Wang", "Frank Lee"];
const DATES      = ["Today", "Yesterday", "2 days ago", "Last week", "2 weeks ago", "Last month"];
const SIZES_KB   = [12, 48, 340, 1200, 4500, 128, 890, 2340, 67, 5600];
const ICON: Record<string, string> = { pdf: "📄", docx: "📝", xlsx: "📊", png: "🖼", jpg: "🖼", mp4: "🎬", txt: "📃", zip: "📦", pptx: "📑", csv: "📊", folder: "📁" };
const TYPE_COLOR: Record<string, string> = { pdf: "#ef4444", docx: "#3b82f6", xlsx: "#22c55e", png: "#ec4899", jpg: "#ec4899", mp4: "#f97316", txt: "#94a3b8", zip: "#a855f7", pptx: "#f59e0b", csv: "#22c55e", folder: "#fbbf24" };

function genFile(i: number) {
  const isFolder = i % 9 === 0;
  const type     = isFolder ? "folder" : FILE_TYPES[i % FILE_TYPES.length];
  const name     = isFolder
    ? `${FILE_NAMES[i % FILE_NAMES.length]} Q${(i % 4) + 1} ${2020 + (i % 5)}`
    : `${FILE_NAMES[i % FILE_NAMES.length]}_v${(i % 4) + 1}.${type}`;
  return {
    id: i,
    name,
    type,
    isFolder,
    size: isFolder ? "—" : `${(SIZES_KB[i % SIZES_KB.length] / 1024).toFixed(1)} MB`,
    owner: OWNERS[i % OWNERS.length],
    modified: DATES[i % DATES.length],
  };
}

// Precompute a page worth of data for the pagination demo
function genPage(page: number, perPage = 20) {
  const start = page * perPage;
  return Array.from({ length: perPage }, (_, j) => genFile(start + j));
}

