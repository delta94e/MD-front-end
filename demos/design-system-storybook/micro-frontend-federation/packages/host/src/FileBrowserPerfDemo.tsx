const ROW_HEIGHT     = 40;
const CONTAINER_H    = 400;
const VISIBLE_COUNT  = Math.ceil(CONTAINER_H / ROW_HEIGHT) + 4; // +4 buffer

function FileRow({ file, style }: { file: ReturnType<typeof genFile>; style?: React.CSSProperties }) {
  return (
    <div style={{
      height: ROW_HEIGHT, display: "flex", alignItems: "center", gap: 10, padding: "0 14px",
      borderBottom: "1px solid #1e293b", fontSize: 12, color: "#94a3b8",
      ...style,
    }}>
      <span style={{ fontSize: 15, width: 20, flexShrink: 0 }}>{ICON[file.type]}</span>
      <span style={{ flex: 1, color: "#f1f5f9", whiteSpace: "nowrap", overflow: "hidden", textOverflow: "ellipsis" }}>{file.name}</span>
      <span style={{ width: 90, color: TYPE_COLOR[file.type], fontSize: 10, fontWeight: 700 }}>{file.type.toUpperCase()}</span>
      <span style={{ width: 70, textAlign: "right" }}>{file.size}</span>
      <span style={{ width: 100, textAlign: "right" }}>{file.owner.split(" ")[0]}</span>
      <span style={{ width: 100, textAlign: "right" }}>{file.modified}</span>
    </div>
  );
}

function VirtualFileList({ total }: { total: number }) {
  const [scrollTop, setScrollTop]   = useState(0);
  const [renderCount, setRenderCount] = useState(0);
  const containerRef = useRef<HTMLDivElement>(null);

  const startIndex   = Math.floor(scrollTop / ROW_HEIGHT);
  const endIndex     = Math.min(startIndex + VISIBLE_COUNT, total);
  const paddingTop   = startIndex * ROW_HEIGHT;
  const paddingBottom = Math.max(0, (total - endIndex) * ROW_HEIGHT);

  // Increment render counter on scroll (demonstrates virtualisation)
  const handleScroll = useCallback((e: React.UIEvent<HTMLDivElement>) => {
    setScrollTop(e.currentTarget.scrollTop);
    setRenderCount(c => c + 1);
  }, []);

  const rows = useMemo(() => {
    const out = [];
    for (let i = startIndex; i < endIndex; i++) {
      out.push(<FileRow key={i} file={genFile(i)} />);
    }
    return out;
  }, [startIndex, endIndex]);

  return (
    <div>
      <div style={{ display: "flex", gap: 16, padding: "8px 14px", background: "#0f172a", borderRadius: "8px 8px 0 0", fontSize: 10, color: "#64748b", fontWeight: 700 }}>
        <span style={{ flex: 1 }}>NAME</span>
        <span style={{ width: 90 }}>TYPE</span>
        <span style={{ width: 70, textAlign: "right" }}>SIZE</span>
        <span style={{ width: 100, textAlign: "right" }}>OWNER</span>
        <span style={{ width: 100, textAlign: "right" }}>MODIFIED</span>
      </div>
      <div
        ref={containerRef}
        onScroll={handleScroll}
        style={{ height: CONTAINER_H, overflowY: "auto", border: "1px solid #334155", borderRadius: "0 0 8px 8px" }}
      >
        <div style={{ paddingTop, paddingBottom }}>
          {rows}
        </div>
      </div>
      <div style={{ display: "flex", gap: 16, marginTop: 8, fontSize: 10, color: "#64748b" }}>
        <span>📂 Total files: <strong style={{ color: "#f1f5f9" }}>{total.toLocaleString()}</strong></span>
        <span>🖼 DOM nodes rendered: <strong style={{ color: "#4ade80" }}>{endIndex - startIndex}</strong></span>
        <span>📍 Scroll position: <strong style={{ color: "#f1f5f9" }}>{Math.round(scrollTop)}px</strong></span>
        <span>↕ First visible row: <strong style={{ color: "#a5b4fc" }}>#{startIndex + 1}</strong></span>
        <span>🔄 Scroll events: <strong style={{ color: "#fbbf24" }}>{renderCount}</strong></span>
      </div>
    </div>
  );
}

// ─────────────────────────────────────────────────────────────────
// Cursor pagination simulation
// ─────────────────────────────────────────────────────────────────

const TOTAL_PAGES = 8;

function usePaginatedFiles() {
  const [pages, setPages]     = useState<ReturnType<typeof genFile>[][]>([]);
  const [cursor, setCursor]   = useState<number>(0);
  const [loading, setLoading] = useState(false);
  const [mode, setMode]       = useState<"offset" | "cursor">("cursor");

  const loadPage = useCallback((pageNum: number) => {
    setLoading(true);
    // Simulate network — "offset" mode is slower because DB scans more rows
    const delay = mode === "offset" ? 900 + pageNum * 180 : 280;
    setTimeout(() => {
      setPages(prev => [...prev, genPage(pageNum)]);
      setCursor(pageNum + 1);
      setLoading(false);
    }, delay);
  }, [mode]);

  const reset = useCallback(() => { setPages([]); setCursor(0); }, []);

  useEffect(() => {
    setPages([]);
    setCursor(0);
  }, [mode]);

  return { pages, cursor, loading, loadPage, reset, hasMore: cursor < TOTAL_PAGES, mode, setMode };
}

